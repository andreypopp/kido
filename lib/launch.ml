type server = Down | Up of string option | Mismatch

type endpoint = {
  tmux : string;
  socket : string;
  protocol : string;
  server : string option;
  expected : string;
}
[@@deriving yojson_of]

let conf_command path args =
  match Tmux.safe "path" path with
  | Error e -> Error ("cannot start a kido server: " ^ e)
  | Ok () ->
      let inner =
        if String.exists (fun c -> Char.equal c ' ' || Char.equal c '\t') path then
          {|"|} ^ path ^ {|"|}
        else path
      in
      Ok ("'" ^ String.concat " " (inner :: args) ^ "'")

let user_conf ~xdg_config_home ~home =
  if not (String.is_empty xdg_config_home) then
    Ok (Filename.concat xdg_config_home "kido/kido.conf")
  else if String.is_empty home then Error "$HOME is not defined"
  else Ok (Filename.concat home ".config/kido/kido.conf")

let server_conf ~exe ~user_conf ~unstamped =
  let open Result.Infix in
  let* kido = conf_command exe [] in
  let* kido_shell = conf_command exe [ "shell" ] in
  if String.exists (String.contains "'\n\r") user_conf then
    Error (Printf.sprintf "cannot source %s: the path contains a quote or a newline" user_conf)
  else
    Ok
      (String.concat ""
         [
           Printf.sprintf
             "# Generated by kido on every launch; edits here are lost.\n\
              # Your own configuration belongs in %s.\n\n"
             user_conf;
           Embedded.tmux_defaults;
           unstamped;
           Printf.sprintf
             "\n\
              # The user's configuration, if there is one: -q, because there\n\
              # usually is not.\n\
              source-file -q '%s'\n"
             user_conf;
           Printf.sprintf
             "\n\
              # What kido owns, set last so nothing above can take it away. The\n\
              # side column and every pane's shell run this kido by the path it\n\
              # was started as, so a second install elsewhere on PATH cannot\n\
              # answer for this server. A default-command the user set above is\n\
              # kept for `kido shell` to run, primed, in place of a bare shell.\n\
              set -gF %s '#{default-command}'\n\
              set -g side-status-command %s\n\
              set -g default-command %s\n"
             Tmux_vars.user_command kido kido_shell;
         ])

let lookup env name =
  Option.get_or ~default:"" (Array.find_map (String.chop_prefix ~pre:(name ^ "=")) env)

let server_env ~bin_dir env =
  let env =
    Array.filter
      (fun s -> not (List.exists (fun pre -> String.prefix ~pre s) [ "KIDO_STATE_DIR=" ]))
      env
  in
  match bin_dir with
  | Some dir -> Shell.with_env env [ ("PATH", Bin_dir.path_with_first dir (lookup env "PATH")) ]
  | None -> env

let digest ~revision ~conf ~env =
  String.concat "\n" (String.trim revision :: conf :: Array.to_list env)
  |> Digest.string |> Digest.to_hex |> String.take 12

let placeholder_env = [| "KIDO_STATE_DIR=/state"; "PATH=/bin" |]

let stamp =
  match server_conf ~exe:"/kido" ~user_conf:"/kido.conf" ~unstamped:"" with
  | Ok conf ->
      digest ~revision:Embedded.fork_revision ~conf
        ~env:(server_env ~bin_dir:(Some "/kido-bin") placeholder_env)
  | Error e -> invalid_arg e

(* tmux's own wording, from client.c, is "protocol version mismatch (client N, server M)": what
   a kido-tmux upgraded under a running server answers every new client until that server
   restarts. *)
let probe_server ~socket bin =
  let ((out, _, err) as p) =
    Unix.open_process_args_full bin
      (Tmux.argv bin
         [
           "-S";
           socket;
           "list-sessions";
           "-F";
           "#{socket_path}\x1f";
           ";";
           "show-environment";
           "-g";
           Tmux_vars.server;
         ])
      (Unix.environment ())
  in
  let stdout = In_channel.input_all out in
  let stderr = In_channel.input_all err in
  match Unix.close_process_full p with
  | _ when String.mem ~sub:"protocol version mismatch" stderr -> Mismatch
  | WEXITED (0 | 1) -> (
      let lines = String.split_on_char '\n' stdout in
      match String.split_on_char '\x1f' (List.hd lines) with
      | [ socket; "" ] when not (String.is_empty socket) ->
          let prefix = Tmux_vars.server ^ "=" in
          let stamp =
            List.find_map
              (fun line ->
                String.chop_prefix ~pre:prefix line
                |> Option.filter (fun value -> not (String.is_empty value)))
              lines
          in
          Up stamp
      | _ -> Down)
  | _ -> Down

let mismatch ~socket bin =
  Printf.sprintf
    "the kido server on socket %S is running an older kido-tmux than this one, so it refuses this \
     client; restart it once its windows are free (detach, then %s -S %s kill-server)"
    socket bin socket

let argv ~socket bin args = Tmux.argv bin ("-S" :: socket :: args)

let new_session ~dir ~env ~detach =
  let open Result.Infix in
  let* user_conf =
    user_conf ~xdg_config_home:(lookup env "XDG_CONFIG_HOME") ~home:(lookup env "HOME")
  in
  let conf = Filename.concat dir "server.conf" in
  let* conf_text =
    server_conf ~exe:(Lazy.force Fs.self) ~user_conf ~unstamped:Embedded.tmux_unstamped
  in
  Fs.write conf conf_text;
  let env =
    Shell.with_env (server_env ~bin_dir:(Bin_dir.own ()) env) [ (Tmux_vars.server, stamp) ]
  in
  Ok (env, [ "-f"; conf; "new-session" ] @ (if detach then [ "-d" ] else []) @ [ "-s"; "main" ])

let run ~dir ~env ~inside =
  let open Result.Infix in
  match inside with
  | Some (e : Tmux.env) ->
      Error (Printf.sprintf "already inside tmux (%s); run kido from a plain terminal" e.socket)
  | None -> (
      let* socket = Server_dir.server_socket ~create:true ~dir in
      let bin = Lazy.force Tmux.binary in
      match probe_server ~socket bin with
      | Mismatch -> Error (mismatch ~socket bin)
      | Up _ -> Unix.execvpe bin (argv ~socket bin [ "attach-session" ]) env
      | Down ->
          let* env, args = new_session ~dir ~env ~detach:false in
          Unix.execvpe bin (argv ~socket bin args) env)

let ensure ~dir ~env =
  let open Result.Infix in
  let* socket = Server_dir.server_socket ~create:true ~dir in
  let bin = Lazy.force Tmux.binary in
  let resolve server =
    let tmux =
      if String.contains bin '/' then Some (Fs.abs bin)
      else Fs.look_path ~path:(lookup env "PATH") bin
    in
    match tmux with
    | Some tmux -> Ok { tmux; socket; protocol = Protocol.value; server; expected = stamp }
    | None -> Error (Printf.sprintf "no %s on PATH" bin)
  in
  match probe_server ~socket bin with
  | Up server -> resolve server
  | Mismatch -> Error (mismatch ~socket bin)
  | Down -> (
      let* env, args = new_session ~dir ~env ~detach:true in
      let ((out, _, err) as p) = Unix.open_process_args_full bin (argv ~socket bin args) env in
      ignore (In_channel.input_all out);
      let stderr = String.trim (In_channel.input_all err) in
      ignore (Unix.close_process_full p);
      match probe_server ~socket bin with
      | Up server -> resolve server
      | Mismatch -> Error (mismatch ~socket bin)
      | Down ->
          Error ("cannot start a kido server" ^ if String.is_empty stderr then "" else ": " ^ stderr)
      )

let%test_module "Tests" =
  (module struct
    let%expect_test "rpc surface" =
      let emit json = print_endline (Yojson.Safe.to_string json) in
      List.iter
        (fun server ->
          emit
            (yojson_of_endpoint
               {
                 tmux = "/bin/kido-tmux";
                 socket = "/server/socket";
                 protocol = Protocol.value;
                 server;
                 expected = "0123456789ab";
               }))
        [ Some "0123456789ab"; Some "other"; None ];
      [%expect
        {|
        {"tmux":"/bin/kido-tmux","socket":"/server/socket","protocol":"6.0","server":"0123456789ab","expected":"0123456789ab"}
        {"tmux":"/bin/kido-tmux","socket":"/server/socket","protocol":"6.0","server":"other","expected":"0123456789ab"}
        {"tmux":"/bin/kido-tmux","socket":"/server/socket","protocol":"6.0","server":null,"expected":"0123456789ab"}
        |}]

    let%expect_test
        "the stamp excludes the unstamped defaults and follows the template, env and fork" =
      let installed ?(revision = Embedded.fork_revision) ?(extra = "") ?(include_unstamped = false)
          exe user_conf bin_dir =
        let conf =
          Result.get_exn (server_conf ~exe ~user_conf ~unstamped:Embedded.tmux_unstamped)
        in
        let conf =
          String.replace ~sub:user_conf ~by:"/kido.conf" (String.replace ~sub:exe ~by:"/kido" conf)
        in
        let conf =
          if include_unstamped then conf
          else String.replace ~sub:Embedded.tmux_unstamped ~by:"" conf
        in
        let env = server_env ~bin_dir:(Some bin_dir) placeholder_env in
        digest ~revision ~conf:(conf ^ extra)
          ~env:(Array.map (String.replace ~sub:bin_dir ~by:"/kido-bin") env)
      in
      let homebrew = installed "/opt/homebrew/bin/kido" "/Users/a/.config/kido/kido.conf" in
      List.iter
        (fun s -> Printf.printf "%b %d\n" (String.equal s stamp) (String.length s))
        [
          homebrew "/opt/homebrew/share/kido/bin";
          installed "/home/b/.local/bin/kido" "/home/b/xdg/kido/kido.conf" "/home/b/share/kido/bin";
          installed ~extra:"set -g mouse off\n" "/opt/homebrew/bin/kido"
            "/Users/a/.config/kido/kido.conf" "/opt/homebrew/share/kido/bin";
          installed ~revision:(String.make 40 '0') "/opt/homebrew/bin/kido"
            "/Users/a/.config/kido/kido.conf" "/opt/homebrew/share/kido/bin";
          installed ~include_unstamped:true "/opt/homebrew/bin/kido"
            "/Users/a/.config/kido/kido.conf" "/opt/homebrew/share/kido/bin";
          digest ~revision:Embedded.fork_revision
            ~conf:(Result.get_exn (server_conf ~exe:"/kido" ~user_conf:"/kido.conf" ~unstamped:""))
            ~env:placeholder_env;
        ];
      [%expect
        {|
        true 12
        true 12
        false 12
        false 12
        false 12
        false 12
        |}]
  end)
