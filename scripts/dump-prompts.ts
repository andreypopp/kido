// dump-prompts.ts prints every piece of text the pi extension puts in
// front of a model: each tool's description, prompt snippet, prompt
// guidelines and parameter descriptions, and the guidelines appended to a
// system prompt. It loads share/pi/ko-pi.ts against a stub of pi's
// ExtensionAPI, the same way the test suite does, so what it prints is what
// pi registers.
//
//   node --experimental-strip-types scripts/dump-prompts.ts > prompts.txt
//
// The texts the extension injects as messages at runtime (a task, an inbound
// message, a steer, a notice, a stream batch, an ending) are built inside
// closures and are listed in the second half by hand.

import { fileURLToPath } from "node:url";

const { createFakePi, withEnv } = await import("../share/pi/ko-pi-fixture.ts");

type Schema = { type?: string; items?: Schema; anyOf?: Schema[]; description?: string };
const typeName = (schema: Schema): string =>
  schema.anyOf ? schema.anyOf.map(typeName).join(" | ") : schema.type === "array" ? `${typeName(schema.items ?? {})}[]` : schema.type ?? "any";

type Tool = {
  name: string;
  description: string;
  promptSnippet?: string;
  promptGuidelines?: string[];
  parameters?: { properties?: Record<string, Schema>; required?: string[] };
};

const { pi, tools: registered, handlers, emit } = createFakePi();
const tools: Tool[] = [];

// A subagent's edge is its environment: its own session id and its parent's.
// A headless ctx (hasUI: false) makes session_start write nothing and open no
// stream, so this dump touches no server and no socket.
process.env.KO_AGENT_SESSION = "dump-session";
process.env.KO_AGENT_PARENT_SESSION = "dump-parent";
delete process.env.KO_PANE;

const { default: extension, RELATION_TEXT, senderHeader, noticeHeader, PARENT_GUIDANCE, SPAWN_RESULT_RULE, SUBAGENT_RESULT_RULE } = await import("../share/pi/ko-pi.ts");
extension(pi as never);
for (const tool of registered.values()) tools.push(tool as Tool);
await emit("session_start", { type: "session_start" }, { hasUI: false, sessionManager: { getSessionId: () => "dump-session", getSessionFile: () => undefined, getBranch: () => [] } });

const out: string[] = ["# What the model sees from ko's pi extension", ""];
out.push(`Generated by scripts/dump-prompts.ts from share/pi/ko-pi.ts. Edit the source, not this file.`, "");

out.push("## Guidelines added to the system prompt (before_agent_start)", "");
const event = { systemPrompt: "<host system prompt>", systemPromptOptions: { promptGuidelines: [] as string[] } };
await withEnv({ KO_SOCKET: "/unused/socket", PATH: fileURLToPath(new URL("../share/ko/bin", import.meta.url)) }, async () => {
  for (const handler of handlers.get("before_agent_start") ?? []) await handler(event);
});
out.push("```", event.systemPromptOptions.promptGuidelines.join("\n\n") || "<none>", "```", "");

out.push("## Tools", "");
for (const t of tools) {
  out.push(`### ${t.name}`, "");
  out.push("description:", "", "```", t.description, "```", "");
  out.push("promptSnippet:", "", "```", t.promptSnippet ?? "<none>", "```", "");
  if (t.promptGuidelines?.length) {
    out.push("promptGuidelines (merged into the system prompt's rules while the tool is registered):", "", "```", t.promptGuidelines.join("\n"), "```", "");
  }
  const props = t.parameters?.properties ?? {};
  const required = new Set(t.parameters?.required ?? []);
  if (Object.keys(props).length === 0) {
    out.push("parameters: none", "");
    continue;
  }
  out.push("parameters:", "");
  for (const [name, schema] of Object.entries(props)) {
    const type = typeName(schema);
    out.push(`- \`${name}\` (${type}${required.has(name) ? ", required" : ""}): ${schema.description ?? "<no description>"}`);
  }
  out.push("");
}

out.push("## Messages the extension injects at runtime", "");
out.push(`Built inside share/pi/ko-pi.ts's closures. \`<from>\` is the sender's name, else its session id, else its pane, else "another agent".`, "");
const relations = Object.entries(RELATION_TEXT).map(([relation, text]) => `${relation}: (${text}):`).join("\n");
const injected: Array<[string, string, string]> = [
  ["a spawned task from the parent (deliverTask)", "the task text verbatim, as a user message, once", "followUp"],
  ["a task from another session (deliverTask)", `${senderHeader("<name>", "sibling")}\n<text> verbatim`, "followUp"],
  ["a message from another agent", `${senderHeader("<name>", "parent")}\n<text> verbatim, as a custom message of type ko-message; the header's relation text by relation:\n${relations}\nthe TUI takes the header back off and shows \"@<name> says:\" with the text, collapsed to its first line until clicked`, "followUp"],
  ["a message with no calling agent", "the text verbatim, unlabelled: no agent is the user speaking", "followUp"],
  ["a user prompt (ko prompt)", "the text verbatim, as the user's own message", "followUp"],
  ["a steer", "<from> is redirecting this work: <text>", "steer"],
  ["a notice (deliverNotice)", `${noticeHeader("<from>")}\n<text> verbatim, as a custom message of type ko-notice; the TUI takes the header back off and shows it collapsed as \"@<from> notifies: <first line>\"`, "steer"],
  ["a stream batch (sendStream)", "job \"<name>\" output (job <id>)\n<the last lines, capped>; when a held line is cut: \"... long lines were truncated (the log has them)\"; with lines dropped: \"... N lines omitted (the log has them)\" first; after the budget is spent: \"... output budget spent; the log has the rest: <log>\"", "steer; starts a turn"],
  ["a moved bash call (executeBash)", "still running after <N> s; it continues as job <id>; a notice arrives when it ends; output so far:\n<the output tail>\nlog: <log>\nFor ctrl+b or /reload, the prefix is only \"still running\".", "tool result, not an error"],
  ["a cancelled async start (async_bash)", "could not start background command: start cancelled by session <reason>; no job was started", "tool result, an error"],
  ["a replaced registry (adoptJobs)", "<N> async_bash jobs of the previous ko-pi version were stopped at /reload: <names>", "notice from ko-pi; only when jobs were stopped"],
  ["an unknown kind", "[unrecognised message kind \"<kind>\" from <from>] <text>", "followUp"],
  ["a child's report (handleNotice)", `${noticeHeader("<child name>")}\n<its last assistant message's text, then the guidance below>; a report over the 4000-byte notice ends with \"\\n\\nfull report: read_report(\\"<child name>\\")\" before the guidance`, "steer"],
  ["a child's empty report (agent_settled)", `subagent "<name>" ended its turn with no message`, "the report text"],
  ["a turn that ended on an error (agent_settled)", "subagent stopped on an error: <text>\nmessage it to retry, or stop_agent to end it", "a status notice"],
  ["the exit notices (session_shutdown, reason quit)", "subagent \"<name>\" is exiting before its first turn ran\nsubagent \"<name>\" is exiting without a report on its last work[: its last turn failed: <text>]", "a status notice"],
  ["a live job's result suffix for a subagent caller", SUBAGENT_RESULT_RULE, "tool result"],
  ["a spawn's result (spawn_agent)", `spawned <name> (session <pi session id>, window <window id>, pane <pane id>); session id is what resume_from takes later; ${SPAWN_RESULT_RULE}. A fork adds \", forked from session <source session id>\" before the semicolon. Toplevel instead ends with \"independent peer; no report or ending notice\".`, "tool result"],
  ["a restart's result (message_agent)", "restarted <name> in pane <pane id>; the same result rule as a spawn follows", "tool result"],
];
for (const [when, text, how] of injected) {
  out.push(`### ${when}`, "", "```", text, "```", how ? `delivered as: ${how}` : "", "");
}
out.push("## Ending notices the extension composes (ko-pi.ts)", "");
out.push("`adoptJobs` builds the job notice; `announceEnding` builds the subagent notice when its pane ended or was removed.", "");
out.push("```", `job "<name>" (<id>) exit <code> | signal <NAME> | failed: <message> | timed out after <N> s
--- last 4000 bytes of its output ---
<the output tail>
log: <log>`, "```", "");
out.push("A stopped job sends no ending notice.", "");
out.push("```", `subagent "<name>" ended: exit <code> | signal <NAME> | failed: <message> | its pane was removed | its pane is gone; it had reported
subagent "<name>" ended: <how>; it had not reported on its last work
--- last 4000 bytes of its screen ---   [only while the pane lingers]
<the screen>
message it to continue it, or stop_agent to end it`, "```", "");
out.push("Every report notice also ends with:", "", "```", PARENT_GUIDANCE, "```", "");
process.stdout.write(out.join("\n"));

