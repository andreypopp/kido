import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer, connect } from 'node:net';
import { once } from 'node:events';
import { createInterface } from 'node:readline';
import { koaChannel, type KoaQuery } from './koa-channel.ts';

test('one channel correlates session scans and completion context, reset cancels stale requests', { timeout: 5000 }, async () => {
  const server = createServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const accepted = once(server, 'connection');
  const client = connect(address.port, '127.0.0.1');
  const [peer] = await accepted;
  const lines = createInterface({ input: peer });
  try {
    const channel = koaChannel(client);
    const next = async (): Promise<KoaQuery> => JSON.parse((await once(lines, 'line'))[0]);
    const send = (reply: object) => peer.write(JSON.stringify(reply) + '\n');
    const incoming = next();
    const first = channel.completionContext(new AbortController().signal);
    const query = await incoming;
    assert.equal(query.type, 'completion_context');
    const listing = next();
    const scan = channel.list('current', new AbortController().signal);
    const list = await listing;
    assert.equal(list.type, 'list');
    assert.notEqual(query.id, list.id);
    send({ type: 'list', id: list.id, rows: [] });
    send({ type: 'completion_context', id: query.id, context: { type: 'runtime', name: 'remote', cwd: '/mapped' } });
    assert.deepEqual(await first, { type: 'runtime', name: 'remote', cwd: '/mapped' });
    assert.deepEqual(await scan, []);
    const signal = channel.signal();
    const pendingQuery = next();
    const pending = channel.completionContext(new AbortController().signal);
    const old = await pendingQuery;
    send({ type: 'reset' });
    assert.deepEqual(await pending, { type: 'unavailable' });
    assert.equal(signal.aborted, true);
    send({ type: 'completion_context', id: old.id, context: { type: 'host', cwd: '/stale' } });
    const freshQuery = next();
    const fresh = channel.completionContext(new AbortController().signal);
    const current = await freshQuery;
    send({ type: 'completion_context', id: current.id, context: { type: 'host', cwd: '/new' } });
    assert.deepEqual(await fresh, { type: 'host', cwd: '/new' });
    const executing = channel.signal();
    channel.cancel();
    assert.equal(executing.aborted, true);
    assert.equal(channel.signal().aborted, false);
    const cancelQuery = next();
    const controller = new AbortController();
    const cancelled = channel.completionContext(controller.signal);
    const cancellable = await cancelQuery;
    const cancellation = next();
    controller.abort();
    assert.deepEqual(await cancellation, { type: 'cancel', id: cancellable.id });
    assert.deepEqual(await cancelled, { type: 'unavailable' });
    channel.close();
  } finally { lines.close(); client.destroy(); peer.destroy(); server.close(); }
});
