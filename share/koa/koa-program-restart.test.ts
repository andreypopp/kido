import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import { Readable } from "node:stream";
import type { NotifyLevel } from "./koa-records.ts";
import { pollUntil, ofType, sse } from "./koa-agent-fixture.ts";
import { fixture, assistantMessage } from "./koa-program-fixture.ts";

type App = Awaited<ReturnType<typeof fixture>>;
const note = (level: NotifyLevel, text: string) => ofType("item", record => record.item.kind === "notify" && record.item.level === level && record.item.text.text === text);
const restart = (app: App) => app.post("prompt", { text: "/restart", mode: "prompt", attachments: [] });
const argvs = async (app: App) => (await app.log()).filter(row => row.type === "argv");
const handled = { disposition: "handled", action: { type: "none" } };
const koa = resolve("../../build/ko/share/ko/koa/koa.ts");

test("/restart starts a new pi on the same session and keeps the transcript", { timeout: 15000 }, async t => {
  const dir = await mkdtemp("/tmp/koa-restart-");
  t.after(() => rm(dir, { recursive: true, force: true }));
  const session = join(dir, "session.jsonl");
  const history = [{ role: "user", timestamp: 1, content: [{ type: "text", text: "seeded question" }] }, { ...assistantMessage, timestamp: 2, content: [{ type: "text", text: "seeded answer" }] }];
  const appended = { role: "user", timestamp: 3, content: [{ type: "text", text: "after restart" }] };
  const app = await fixture(t, [{ type: "respond", command: "get_state", data: { sessionFile: session } }, { type: "respond", command: "get_messages", data: { messages: history } }, { type: "wait", command: "prompt", events: [{ type: "message_start", message: appended }, { type: "message_end", message: appended }] }], { KOA_FAKE_RESTART_FILE: join(dir, "restart-state") }, undefined, true, [], koa);
  await writeFile(join(dir, "restart-state"), JSON.stringify({ type: "blocked", jobs: 1, children: 0 }));
  await restart(app);
  await app.until(note("info", "restart waits for 1 job"));
  await writeFile(join(dir, "restart-state"), JSON.stringify({ type: "ready" }));
  assert.deepEqual(await (await restart(app)).json(), handled);
  await app.until(note("info", "pi restarted"));
  const rows = await argvs(app);
  assert.equal(rows.length, 2);
  assert.equal(rows[1].args[rows[1].args.indexOf("--session") + 1], session);
  const seen = app.records().filter(record => record.type === "state").map(record => record.pi.type);
  assert.ok(seen.includes("restarting") && seen.includes("starting"));
  const events = new AbortController();
  t.after(() => events.abort());
  const fresh = sse(Readable.from((await fetch(app.base + "events", { signal: events.signal })).body ?? []));
  const first = await fresh.until(ofType("reset"));
  const shown = JSON.stringify(first.items);
  assert.ok(shown.includes("seeded question") && shown.includes("seeded answer") && shown.includes("restart waits for 1 job"));
  await app.post("prompt", { text: "go", mode: "prompt", attachments: [] });
  await fresh.until(ofType("item", record => record.item.kind === "user" && record.item.text === "after restart"));
  assert.doesNotMatch(app.stderr(), /not serving/);
  assert.equal((await app.post("quit")).status, 200);
  assert.equal((await app.close)[0], 0);
});

test("/restart defers for jobs, subagents, no answer and no session, and is refused while busy", { timeout: 20000 }, async t => {
  const dir = await mkdtemp("/tmp/koa-restart-");
  t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, "restart-state");
  const answer = (value: object) => writeFile(file, JSON.stringify(value));
  const bare = await fixture(t, [], {}, undefined, true, [], koa);
  assert.deepEqual(await (await restart(bare)).json(), handled);
  await bare.until(note("info", "restart needs a saved session"));
  const app = await fixture(t, [{ type: "respond", command: "get_state", data: { sessionFile: join(dir, "session.jsonl") } }, { type: "wait", command: "prompt", events: [{ type: "agent_start" }] }], { KOA_FAKE_RESTART_FILE: file }, undefined, true, [], koa);
  await answer({ type: "blocked", jobs: 3, children: 1 });
  await restart(app);
  await app.until(note("info", "restart waits for 3 jobs"));
  await answer({ type: "blocked", jobs: 1, children: 2 });
  await restart(app);
  await app.until(note("info", "restart waits for 1 job"));
  await answer({ type: "blocked", jobs: 0, children: 2 });
  await restart(app);
  await app.until(note("info", "restart waits for 2 subagents to report"));
  await answer({ type: "blocked", jobs: 0, children: 1 });
  await restart(app);
  await app.until(note("info", "restart waits for 1 subagent to report"));
  await answer({ type: "silent" });
  const sent = Date.now();
  await restart(app);
  await app.until(note("info", "restart waits; the extension did not answer, try /restart again"));
  assert.ok(Date.now() - sent < 3000);
  await answer({ type: "ready" });
  await app.post("prompt", { text: "work", mode: "prompt", attachments: [] });
  await app.until(ofType("state", record => record.working === true));
  assert.deepEqual(await (await restart(app)).json(), handled);
  await app.until(note("warning", "restart: not while a turn, a command, a queue, a dialog or an editor is open"));
  assert.equal((await argvs(app)).length, 1);
  await pollUntil(async () => (await bare.log()).length > 0, 5000, "the log");
  assert.equal((await argvs(bare)).length, 1);
});

test("koa stopping during /restart does not start a new pi", { timeout: 15000 }, async t => {
  const dir = await mkdtemp("/tmp/koa-restart-");
  t.after(() => rm(dir, { recursive: true, force: true }));
  const app = await fixture(t, [{ type: "respond", command: "get_state", data: { sessionFile: join(dir, "session.jsonl") } }], { KOA_FAKE_STUBBORN: "1", KOA_PI_EXIT_MS: "300" }, undefined, true, [], koa);
  void restart(app).catch(() => {});
  await app.until(ofType("state", record => record.pi.type === "restarting"));
  assert.equal((await app.post("quit")).status, 200);
  assert.equal((await app.close)[0], 0);
  assert.equal((await argvs(app)).length, 1);
});

test("a pi that fails to start leaves the exit card and an error note", { timeout: 15000 }, async t => {
  const dir = await mkdtemp("/tmp/koa-restart-");
  t.after(() => rm(dir, { recursive: true, force: true }));
  const fail = join(dir, "fail");
  const app = await fixture(t, [{ type: "respond", command: "get_state", data: { sessionFile: join(dir, "session.jsonl") } }], { KOA_FAKE_FAIL_FILE: fail }, undefined, true, [], koa);
  await writeFile(fail, "");
  await restart(app);
  await app.until(ofType("item", record => record.item.kind === "notify" && record.item.level === "error" && record.item.text.text.startsWith("pi did not start: ")));
  const state = await app.until(ofType("state", record => record.pi.type === "exited"));
  assert.equal("exited" in state.pi && state.pi.exited, 3);
});
