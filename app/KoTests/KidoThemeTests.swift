import GhosttyKit
import KidoTheme
import XCTest

// Generates Packages/KidoTheme/Sources/KidoTheme/KidoTheme.swift from the kido theme files: make kido-theme.
// Without KO_RECORD_FIXTURES it checks that the committed file is current.
@MainActor final class KidoThemeTests: XCTestCase {
    private struct RGB: Equatable {
        let r, g, b: UInt8
        init(r: UInt8, g: UInt8, b: UInt8) { (self.r, self.g, self.b) = (r, g, b) }
        init(_ color: KidoTheme.RGB) { self.init(r: color.r, g: color.g, b: color.b) }
    }
    private typealias Colors = (background: RGB, foreground: RGB, failure: RGB, blue: RGB)

    private static let app = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()

    private func parse(_ name: String) throws -> Colors {
        XCTAssertEqual(ghostty_init(0, nil), GHOSTTY_SUCCESS)
        let path = Self.app.appendingPathComponent("Resources/ghostty/themes/" + name).path
        let text = try String(contentsOfFile: path, encoding: .utf8)
        let config = try XCTUnwrap(ghostty_config_new())
        defer { ghostty_config_free(config) }
        ghostty_config_load_string(config, text, UInt(text.utf8.count), path)
        let diagnostics = ghostty_config_diagnostics_count(config)
        try XCTUnwrap(diagnostics == 0 ? true : nil, "\(name) has \(diagnostics) diagnostics")
        func color(_ key: String) throws -> RGB {
            var value = ghostty_config_color_s()
            try XCTUnwrap(ghostty_config_get(config, &value, key, UInt(key.utf8.count)) ? true : nil, key)
            return RGB(r: value.r, g: value.g, b: value.b)
        }
        var palette = ghostty_config_palette_s()
        try XCTUnwrap(ghostty_config_get(config, &palette, "palette", 7) ? true : nil, "palette")
        let entries = withUnsafePointer(to: &palette.colors) { pointer in
            pointer.withMemoryRebound(to: ghostty_config_color_s.self, capacity: 256) { Array(UnsafeBufferPointer(start: $0, count: 16)) }
        }
        return (try color("background"), try color("foreground"), RGB(r: entries[1].r, g: entries[1].g, b: entries[1].b), RGB(r: entries[4].r, g: entries[4].g, b: entries[4].b))
    }

    private func render(_ name: String, _ colors: Colors) -> String {
        func rgb(_ color: RGB) -> String { "RGB(r: \(color.r), g: \(color.g), b: \(color.b))" }
        return "    public static let \(name) = KidoTheme(background: \(rgb(colors.background)), foreground: \(rgb(colors.foreground)), failure: \(rgb(colors.failure)), blue: \(rgb(colors.blue)))\n"
    }

    func testTheGeneratedFileMatchesTheThemeFiles() throws {
        let light = try parse("kido-light")
        let dark = try parse("kido-dark")
        let source = """
        // Generated by `make -C app kido-theme` from the kido-light and kido-dark theme files.
        public struct KidoTheme: Equatable, Sendable {
            public struct RGB: Equatable, Sendable {
                public let r, g, b: UInt8
            }
            public let background, foreground, failure, blue: RGB

        """ + render("light", light) + render("dark", dark) + "}\n"
        if let destination = ProcessInfo.processInfo.environment["KO_RECORD_FIXTURES"], !destination.isEmpty {
            try source.write(toFile: destination + "/KidoTheme/Sources/KidoTheme/KidoTheme.swift", atomically: true, encoding: .utf8)
            return
        }
        let committed = try String(contentsOf: Self.app.appendingPathComponent("Packages/KidoTheme/Sources/KidoTheme/KidoTheme.swift"), encoding: .utf8)
        XCTAssertEqual(committed, source)
        for (theme, colors) in [(KidoTheme.light, light), (KidoTheme.dark, dark)] {
            XCTAssertEqual([theme.background, theme.foreground, theme.failure, theme.blue].map(RGB.init), [colors.background, colors.foreground, colors.failure, colors.blue])
        }
    }
}
